  const KEY = 'pourmatch_lang';

  function detect() {
    const saved = localStorage.getItem(KEY);
    if (saved === 'zh' || saved === 'en') return saved;
    return String(navigator.language || '').toLowerCase().startsWith('zh') ? 'zh' : 'en';
  }

  let lang = detect();

  // 缺字時退回中文，再退回 key 本身，避免畫面出現空白
  function t(key, vars) {
    let s = (DICT[lang] && DICT[lang][key]) ?? DICT.zh[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
    return s;
  }

  function apply(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(el => {
      el.textContent = t(el.dataset.i18n);
    });
    scope.querySelectorAll('[data-i18n-html]').forEach(el => {
      el.innerHTML = t(el.dataset.i18nHtml);
    });
    scope.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      el.placeholder = t(el.dataset.i18nPlaceholder);
    });
    scope.querySelectorAll('[data-i18n-title]').forEach(el => {
      el.title = t(el.dataset.i18nTitle);
    });
    const pageTitle = document.querySelector('meta[name="i18n-title"]');
    if (pageTitle) document.title = t(pageTitle.content);
  }

  function setLang(next) {
    if (next !== 'zh' && next !== 'en') return;
    lang = next;
    localStorage.setItem(KEY, next);
    document.documentElement.lang = next === 'zh' ? 'zh-Hant' : 'en';
    apply();
    syncToggle();
    // 由各頁面自行重繪動態內容
    window.dispatchEvent(new CustomEvent('pourmatch:langchange', { detail: { lang: next } }));
  }

  function syncToggle() {
    document.querySelectorAll('.lang-label').forEach(el => { el.textContent = t('nav.language'); });
  }

  // 導覽列的「語言」項目：連往獨立的語言頁，不在原地切換
  function mountToggle() {
    if (document.querySelector('.nav-lang')) return;
    if (location.pathname.endsWith('language.html')) return;

    const navList = document.querySelector('.nav-links');
    const link = document.createElement('a');
    link.href = 'language.html';
    link.className = 'lang-link';
    link.innerHTML = `<span class="lang-label"></span>`;

    if (navList) {
      const li = document.createElement('li');
      li.className = 'nav-lang';
      li.appendChild(link);
      navList.appendChild(li);
    } else {
      // 展示頁沒有主選單
      const bar = document.querySelector('.sc-top') || document.querySelector('.navbar');
      if (!bar) return;
      link.classList.add('nav-lang');
      bar.appendChild(link);
    }
    syncToggle();
  }

